// 把 `assets/app-icons/<名字>.png` 烘成一块屏能直接画的东西。
//
// 这是 `app-launcher/build.rs` 里那套做法的精简版，挪出来给应用页自己用：应用要把自己的标志
// 画在标题前面，而它们不能依赖外壳（外壳依赖它们）。烘出来的形状一样 —— RGB565 + 8 位 alpha，
// 静态数组，运行时没有解码器、没有分配。
//
// 用 `include!` 引进各自的 `build.rs`：
//
// ```ignore
// include!("../build_support/bake.rs");
//
// fn main() {
//     bake("deepseek.png", "DEEPSEEK", 72);
// }
// ```

use std::env;
use std::fs::File;
use std::io::Write;
use std::path::{Path, PathBuf};

/// 圆角占边长的比例。和外壳、和 iOS 的做法一致。
const SQUIRCLE_RADIUS_RATIO: f32 = 0.225;

/// 烘一个图标，写进 `$OUT_DIR/baked_icon.rs`。
///
/// `ident` 是生成的常量前缀（`DEEPSEEK` → `DEEPSEEK_RGB` / `DEEPSEEK_ALPHA` / `DEEPSEEK_SIZE`）；
/// `size` 是烘出来的边长 —— 标题旁边一个 28 点的标志不需要 118 点那么多像素。
pub fn bake(file: &str, ident: &str, size: u32) {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let source = manifest_dir.join("../../assets/app-icons").join(file);

    println!("cargo:rerun-if-changed={}", source.display());
    println!("cargo:rerun-if-changed=../build_support/bake.rs");

    let mut out = File::create(out_dir.join("baked_icon.rs")).expect("failed to create baked_icon.rs");

    writeln!(out, "// Auto-generated by build.rs. Do not edit.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#[allow(dead_code)]").unwrap();
    writeln!(out, "pub mod baked {{").unwrap();

    match bake_one(&mut out, &source, ident, size) {
        Ok(()) => {}
        Err(error) => {
            // 没有图就不烘：一个应用的标题前面少一张图，比一次构建失败轻。
            eprintln!("cargo:warning=cannot bake {}: {}", source.display(), error);
        }
    }

    writeln!(out, "}}").unwrap();
}

/// 一张图的烘焙本身。写进调用方给的句柄 —— 同一个句柄才保证数组落在 `mod baked` 里面。
fn bake_one(
    out: &mut File,
    path: &Path,
    ident: &str,
    size: u32,
) -> Result<(), Box<dyn std::error::Error>> {
    let image = image::open(path)?;
    let rgba = image.to_rgba8();
    let (w, h) = rgba.dimensions();

    let crop = w.min(h);
    let cropped = image::imageops::crop_imm(&rgba, (w - crop) / 2, (h - crop) / 2, crop, crop)
        .to_image();
    let resized = image::imageops::resize(
        &cropped,
        size,
        size,
        image::imageops::FilterType::Lanczos3,
    );

    let mask = squircle_mask(size);
    let stride = size as usize;
    let total = stride * stride;

    let mut colors = Vec::with_capacity(total);
    let mut alphas = Vec::with_capacity(total);

    for (index, pixel) in resized.pixels().enumerate() {
        let rgb = dither(pixel[0], pixel[1], pixel[2], index % stride, index / stride);
        let alpha = (pixel[3] as u32 * mask[index] as u32 / 255) as u8;

        colors.push(rgb);
        alphas.push(alpha);
    }

    writeln!(out, "    pub static {ident}_RGB: [u16; {total}] = [")?;
    for chunk in colors.chunks(16) {
        write!(out, "       ")?;
        for value in chunk {
            write!(out, " 0x{value:04X},")?;
        }
        writeln!(out)?;
    }
    writeln!(out, "    ];")?;
    writeln!(out)?;

    writeln!(out, "    pub static {ident}_ALPHA: [u8; {total}] = [")?;
    for chunk in alphas.chunks(24) {
        write!(out, "       ")?;
        for value in chunk {
            write!(out, " 0x{value:02X},")?;
        }
        writeln!(out)?;
    }
    writeln!(out, "    ];")?;
    writeln!(out)?;

    writeln!(out, "    pub const {ident}_SIZE: u16 = {size};")?;
    writeln!(out)?;

    Ok(())
}

/// 4×4 超采样的超椭圆（squircle）alpha 掩膜。
fn squircle_mask(size: u32) -> Vec<u8> {
    const SUPERSAMPLE: usize = 4;
    const SAMPLES: f32 = (SUPERSAMPLE * SUPERSAMPLE) as f32;

    let n = size as usize;
    let mut mask = vec![0u8; n * n];

    let half = size as f32 * 0.5;
    let radius = SQUIRCLE_RADIUS_RATIO * size as f32;
    let inner = half - radius;

    for y in 0..n {
        for x in 0..n {
            let mut coverage = 0.0f32;

            for sy in 0..SUPERSAMPLE {
                let sub_y = y as f32 + (sy as f32 + 0.5) / SUPERSAMPLE as f32;
                let qy = ((sub_y - half).abs() - inner).max(0.0);

                for sx in 0..SUPERSAMPLE {
                    let sub_x = x as f32 + (sx as f32 + 0.5) / SUPERSAMPLE as f32;
                    let qx = ((sub_x - half).abs() - inner).max(0.0);
                    let distance = (qx * qx + qy * qy).sqrt();

                    coverage += if distance <= radius - 1.0 {
                        1.0
                    } else if distance < radius {
                        radius - distance
                    } else {
                        0.0
                    };
                }
            }

            mask[y * n + x] = ((coverage / SAMPLES) * 255.0 + 0.5) as u8;
        }
    }

    mask
}

/// Bayer 8×8 的抖动偏移，和 `pomelo_gfx::color::DITHER_OFFSETS` 同一张表。
const DITHER: [f32; 64] = [
    0.9921875, 0.4921875, 0.8671875, 0.3671875, 0.9609375, 0.4609375, 0.8359375, 0.3359375,
    0.2421875, 0.7421875, 0.1171875, 0.6171875, 0.2109375, 0.7109375, 0.0859375, 0.5859375,
    0.8046875, 0.3046875, 0.9296875, 0.4296875, 0.7734375, 0.2734375, 0.8984375, 0.3984375,
    0.0546875, 0.5546875, 0.1796875, 0.6796875, 0.0234375, 0.5234375, 0.1484375, 0.6484375,
    0.9453125, 0.4453125, 0.8203125, 0.3203125, 0.9765625, 0.4765625, 0.8515625, 0.3515625,
    0.1953125, 0.6953125, 0.0703125, 0.5703125, 0.2265625, 0.7265625, 0.1015625, 0.6015625,
    0.7578125, 0.2578125, 0.8828125, 0.3828125, 0.7890625, 0.2890625, 0.9140625, 0.4140625,
    0.0078125, 0.5078125, 0.1328125, 0.6328125, 0.0390625, 0.5390625, 0.1640625, 0.6640625,
];

/// 8 位 RGB → RGB565，带有序抖动：这块屏是 16 位的，一块纯色渐变不抖会起带子。
fn dither(r: u8, g: u8, b: u8, x: usize, y: usize) -> u16 {
    let r_index = ((y & 7) << 3) | (x & 7);
    let g_index = (((y + 4) & 7) << 3) | ((x + 2) & 7);
    let b_index = (((y + 2) & 7) << 3) | ((x + 4) & 7);

    let r5 = ((r as f32 * 0.125 + DITHER[r_index]) as u32).min(31) as u16;
    let g6 = ((g as f32 * 0.250 + DITHER[g_index]) as u32).min(63) as u16;
    let b5 = ((b as f32 * 0.125 + DITHER[b_index]) as u32).min(31) as u16;

    (r5 << 11) | (g6 << 5) | b5
}
